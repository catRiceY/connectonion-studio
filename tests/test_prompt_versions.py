def test_baseline_read_is_pure_and_does_not_execute_script(store, directory):
    before = set(directory.rglob("*"))
    (directory / "agent.py").write_text(SCRIPT + '\nraise RuntimeError("must not execute")\n')
    state = store.state()
    assert state["supported"] and state["current"]["id"] == "baseline"
    assert state["current"]["text"] == "Original instructions"
    assert state["versions"] == []
    assert set(directory.rglob("*")) == before
    assert store.get("baseline") == state["current"]


def test_save_list_restore_are_immutable_and_do_not_rewrite_script(store, directory):
    script = (directory / "agent.py").read_bytes()
    first = store.save("baseline", "  First instructions\n")["current"]
    first_bytes = (store.root / f"{first['id']}.json").read_bytes()
    second = store.save(first["id"], "Second instructions")["current"]
    restored = store.save(second["id"], restore=first["id"])
    current = restored["current"]
    assert current["text"] == first["text"] == "First instructions"
    assert current["id"] not in {first["id"], second["id"]}
    assert current["parent_id"] == second["id"] and current["restored_from"] == first["id"]
    assert len(restored["versions"]) == 3
    assert all("text" not in item for item in restored["versions"])
    assert store.get(first["id"]) == first
    assert (store.root / f"{first['id']}.json").read_bytes() == first_bytes
    assert (directory / "agent.py").read_bytes() == script
    assert store.save(current["id"], restore="baseline")["current"]["text"] == "Original instructions"


def test_concurrent_writers_have_one_winner(store):
    def save(text):
        try:
            return store.save("baseline", text)
        except PromptConflict:
            return None
    with ThreadPoolExecutor(max_workers=2) as pool:
        results = list(pool.map(save, ["First writer", "Second writer"]))
    assert sum(result is not None for result in results) == 1
    assert len(store.state()["versions"]) == 1


