@pytest.mark.parametrize("mutation", ["text", "sha256", "pointer", "parent", "cycle", "date"])
def test_corruption_fails_closed(store, mutation):
    version = store.save("baseline", "New instructions")["current"]
    path = store.root / f"{version['id']}.json"
    if mutation == "text":
        (store.root / f"{version['id']}.prompt").write_text("tampered")
    elif mutation == "pointer":
        store.pointer.write_text('{"version_id":"../../secret"}')
    else:
        data = json.loads(path.read_text())
        data[{"sha256": "sha256", "parent": "parent_id", "cycle": "parent_id", "date": "created_at"}[mutation]] = (
            version["id"] if mutation == "cycle" else "invalid")
        path.write_text(json.dumps(data))
    with pytest.raises(PromptError):
        store.state()
    with pytest.raises(PromptError):
        wrap_host_for_prompt(lambda *_: None, store.script)


@pytest.mark.parametrize("target", ["root", "pointer", "version", "script", "lock"])
def test_symlinks_are_rejected(store, directory, tmp_path, target):
    version = store.save("baseline", "New instructions")["current"]
    outside = tmp_path / "outside"
    outside.write_text("unchanged")
    path = {"root": store.root, "pointer": store.pointer,
            "version": store.root / f"{version['id']}.prompt", "script": store.script,
            "lock": directory / ".studio-prompts.lock"}[target]
    if path.is_dir():
        path.rename(directory / "preserved-prompts")
        outside = tmp_path / "outside-directory"
        outside.mkdir()
    else:
        path.unlink()
    path.symlink_to(outside)
    with pytest.raises(PromptError):
        store.save(version["id"], "Must not save") if target == "lock" else store.state()
    if outside.is_file():
        assert outside.read_text() == "unchanged"


