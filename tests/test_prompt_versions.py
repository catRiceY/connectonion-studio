def fake_factory(directory, monkeypatch):
    # This fixture tests selection freezing only; the separate provenance
    # contracts use the real framework Agent and a scripted offline provider.
    monkeypatch.setattr("co_studio.prompt_provenance.attach_provenance", lambda agent, **_: agent)
    class FakeAgent:
        def __init__(self, *, name, system_prompt):
            self.system_prompt = (system_prompt.read_text().strip() if isinstance(system_prompt, Path) else system_prompt) + "\nPlugin suffix"
    module = types.ModuleType("connectonion")
    module.Agent = FakeAgent
    monkeypatch.setitem(sys.modules, "connectonion", module)
    namespace = {"__file__": str(directory / "agent.py"), "__name__": "synthetic"}
    exec(compile((directory / "agent.py").read_text(), str(directory / "agent.py"), "exec"), namespace)
    return namespace["create_agent"]


def test_runtime_freezes_revision_keeps_plugins_and_leaves_files_and_old_history(store, directory, monkeypatch):
    original_script = store.script.read_bytes()
    history = directory / "old-history.json"
    history.write_text('{"messages":[{"role":"system","content":"old"}]}')
    host = lambda factory, **kwargs: factory
    assert wrap_host_for_prompt(host, store.script) is host
    first = store.save("baseline", "First")["current"]
    wrapped = wrap_host_for_prompt(host, store.script)
    factory = fake_factory(directory, monkeypatch)
    frozen_factory = wrapped(factory, co_dir=directory / ".co")
    assert frozen_factory().system_prompt == "First\nPlugin suffix"
    store.save(first["id"], "Second")
    assert frozen_factory().system_prompt == "First\nPlugin suffix"
    restarted = wrap_host_for_prompt(host, store.script)(fake_factory(directory, monkeypatch), co_dir=directory / ".co")
    assert restarted().system_prompt == "Second\nPlugin suffix"
    assert store.script.read_bytes() == original_script
    assert json.loads(history.read_text())["messages"][0]["content"] == "old"
    (store.root / f"{first['id']}.prompt").write_text("tampered")
    with pytest.raises(PromptError):
        frozen_factory()


