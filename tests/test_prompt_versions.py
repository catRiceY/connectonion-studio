def test_api_crud_conflict_and_cache(client, directory):
    response = client.get("/api/agents/demo/prompts")
    assert response.status_code == 200 and response.headers["cache-control"] == "no-store"
    assert not (directory / ".studio-prompts").exists()
    first = client.post("/api/agents/demo/prompts", json={"base_version": "baseline", "text": "First"})
    assert first.status_code == 200
    identity = first.json()["current"]["id"]
    assert client.get(f"/api/agents/demo/prompts/{identity}").json()["text"] == "First"
    assert client.post("/api/agents/demo/prompts", json={"base_version": "baseline", "text": "stale"}).status_code == 409
    response = client.post("/api/agents/demo/prompts/restore", json={"base_version": identity, "version_id": "baseline"})
    assert response.status_code == 200 and response.json()["current"]["restored_from"] == "baseline"
    assert client.get("/api/agents/demo/prompts/unknown").status_code == 404
    assert client.post("/api/agents/demo/prompts", json={"base_version": identity, "text": "x", "path": "/tmp"}).status_code == 422


