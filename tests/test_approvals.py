def test_api_roundtrip_strict_body_and_origin(client, directory):
    base = "/api/agents/demo"
    assert client.get(base + "/tools/config").json()["revision"] == 0
    body = {"expected_revision": 0, "mcp_enabled": True, "approvals_enabled": True,
            "approval_timeout_seconds": 30, "context_budget": 4096}
    assert client.put(base + "/tools/config", json=body).status_code == 200
    assert client.put(base + "/tools/config", json=body).status_code == 409
    assert client.put(base + "/tools/config", json=body | {"unexpected": 1}).status_code == 422
    assert client.put(base + "/tools/config", json=body, headers={"Origin": "https://evil.example"}).status_code == 403
    row = request(ApprovalStore(directory))
    assert client.get(base + "/approvals").json()["total"] == 1
    decision = base + f"/approvals/{row['id']}/decision"
    assert client.post(decision, json={"decision": "approve", "binding": "0" * 64}).status_code == 409
    assert client.post(decision, json={"decision": "approve", "binding": row["binding"]}).json()["status"] == "approved"
    assert client.get(base + "/approvals").json()["total"] == 0
    assert client.get(base + "/approvals?status=all").json()["total"] == 1
