def test_approval_bound_redacted_idempotent_and_consume_once(directory):
    store = ApprovalStore(directory)
    assert store.list() == {"items": [], "total": 0} and not store.path.exists()
    row = request(store, arguments={"text": "note", "password": "do-not-store"})
    assert row["arguments"]["password"] == "[REDACTED]"
    assert b"do-not-store" not in store.path.read_bytes()
    assert request(store, arguments={"text": "note", "password": "do-not-store"})["id"] == row["id"]
    changed = request(store, arguments={"text": "different"})
    assert changed["binding"] != row["binding"]
    with pytest.raises(ToolsConflict):
        store.decide(row["id"], binding=changed["binding"], decision="approve")
    approved = store.decide(row["id"], binding=row["binding"], decision="approve")
    assert approved["status"] == "approved"
    assert store.decide(row["id"], binding=row["binding"], decision="approve") == approved
    with pytest.raises(ToolsConflict):
        store.decide(row["id"], binding=row["binding"], decision="reject")
    assert store.consume(row["id"], row["binding"])["status"] == "executing"
    with pytest.raises(ToolsConflict):
        store.consume(row["id"], row["binding"])
    assert store.finish(row["id"], "succeeded")["status"] == "succeeded"
    assert store.decide(row["id"], binding=row["binding"], decision="approve")["status"] == "succeeded"
    assert store.path.stat().st_mode & 0o777 == 0o600


def test_expiry_and_dead_process_outcome(directory):
    now = [100.0]
    store = ApprovalStore(directory, clock=lambda: now[0])
    expired = request(store, ttl=1)
    now[0] += 2
    assert store.get(expired["id"])["status"] == "expired"
    with pytest.raises(ToolsConflict):
        store.decide(expired["id"], binding=expired["binding"], decision="approve")
    active = request(store, call_id="call-2")
    store.decide(active["id"], binding=active["binding"], decision="approve")
    store.consume(active["id"], active["binding"])
    with sqlite3.connect(store.path) as db:
        db.execute("UPDATE approvals SET owner_created=0 WHERE id=?", (active["id"],))
    assert store.get(active["id"])["status"] == "unknown"


def test_concurrent_decisions_choose_one_and_cross_agent_rejected(directory):
    store = ApprovalStore(directory)
    row = request(store)
    def decide(value):
        try:
            return store.decide(row["id"], binding=row["binding"], decision=value)["decision"]
        except ToolsConflict:
            return "conflict"
    with ThreadPoolExecutor(2) as pool:
        values = list(pool.map(decide, ["approve", "reject"]))
    assert values.count("conflict") == 1
    other = directory.parent / "other"
    other.mkdir()
    with pytest.raises(ToolsNotFound):
        ApprovalStore(other).decide(row["id"], binding=row["binding"], decision="approve")


