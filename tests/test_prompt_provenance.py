def test_abandoned_worker_cannot_append_after_terminal_or_bind_to_next_turn(runtime, monkeypatch):
    _, _, first, _ = runtime
    llm = ScriptedLLM([response("Late abandoned result"), response("Current answer")])
    agent = factory_for(runtime, first, llm)()
    abandoned = []

    def interruptible(fn, io, **kwargs):
        if not abandoned:
            abandoned.append((copy_context(), fn))
            return None, True
        # The old worker begins only after a new llm_call is pending. Its
        # inherited context must prevent it from consuming that call's proof.
        old_context, old_fn = abandoned[0]
        old_context.run(old_fn)
        return fn(), False

    monkeypatch.setattr("connectonion.core.agent.run_interruptible", interruptible)
    agent.input("Cancelled", session={"session_id": "prompt-session"})
    assert events(agent.current_session) == []
    first_trace = deepcopy(agent.current_session["trace"])
    agent.input("Next", session=deepcopy(agent.current_session))
    observed = events(agent.current_session)
    assert len(observed) == 1 and observed[0]["turn"] == 2
    assert agent.current_session["trace"][:len(first_trace)] == first_trace
    assert agent.current_session["trace"][-1]["type"] == "turn_result"


def test_host_provider_failure_does_not_invent_durable_evidence(runtime):
    _, _, first, _ = runtime
    agents = []
    factory = factory_for(runtime, first, ScriptedLLM([RuntimeError("Synthetic provider error")]), agents=agents)
    with pytest.raises(RuntimeError, match="Synthetic provider error"):
        run(runtime, factory)
    in_memory = events(agents[0].current_session)
    assert len(in_memory) == 1 and in_memory[0]["status"] == "bound"
    assert agents[0].current_session["trace"][-1]["type"] == "turn_result"
    # ConnectOnion's no-connection error path saves the claimed session, not
    # the Agent's later runtime copy. We do not backfill or claim persistence.
    assert latest(runtime)["status"] == "failed"
    assert events(latest(runtime)["session"]) == []


def test_generated_runner_factory_wires_observer_without_rewriting_script(runtime):
    directory, store, first, _ = runtime
    script_bytes = store.script.read_bytes()
    llm = ScriptedLLM([response("Answer")])
    namespace = {"__file__": str(store.script), "__name__": "offline_generated",
                 "OFFLINE_LLM": llm, "CO_DIR": directory / ".co"}
    exec(compile(script_bytes, str(store.script), "exec"), namespace)
    factory = wrap_host_for_prompt(lambda create_agent, **_: create_agent, store.script)(
        namespace["create_agent"], co_dir=directory / ".co")
    observed = events(run(runtime, factory)["session"])
    assert len(observed) == 1 and observed[0]["version_id"] == first["id"]
    assert store.script.read_bytes() == script_bytes


def test_hash_ignores_only_domain_ids_preserves_order_and_developer_roles():
    original = [{"id": "co-id", "role": "system", "content": "Private"}]
    assert system_sha256(original) == system_sha256([{k: v for k, v in original[0].items() if k != "id"}])
    assert system_sha256(original) != system_sha256(original + [{"role": "developer", "content": "More"}])
    assert system_sha256(original) != hashlib.sha256(b"Private").hexdigest()
