def factory_for(runtime, revision, llm, *, on_events=(), tools=(), agents=None):
    directory = runtime[0]

    def factory():
        agent = Agent("Prompt contract", system_prompt=revision["text"], llm=llm,
                      quiet=True, log=False, co_dir=directory / ".co", state_dir=directory / ".co",
                      on_events=list(on_events), tools=list(tools), max_iterations=3)
        attach_provenance(agent, agent_dir=directory, revision=revision)
        if agents is not None:
            agents.append(agent)
        return agent

    return factory


def run(runtime, factory, prompt="Question", session=None):
    return input_handler(factory, runtime[3], prompt, result_ttl=3600,
                         session=session or {"session_id": "prompt-session"})


def events(session):
    return [event for event in session["trace"] if event.get("type") == "prompt_provenance"]


def latest(runtime):
    return json.loads(runtime[3].path.read_text().splitlines()[-1])


def test_real_host_two_turns_match_actual_provider_inputs(runtime):
    directory, store, first, storage = runtime
    llm = ScriptedLLM([response("First answer"), response("Second answer")])
    factory = factory_for(runtime, first, llm)
    run(runtime, factory)
    result = run(runtime, factory, "Followup")
    observations = events(result["session"])
    assert [item["turn"] for item in observations] == [1, 2]
    assert [item["status"] for item in observations] == ["bound", "bound"]
    assert [item["reason"] for item in observations] == ["new_session", "restored_session"]
    verifier = event_verifier(directory)
    for observation, supplied in zip(observations, llm.inputs):
        assert observation["version_id"] == observation["launch_version_id"] == first["id"]
        assert observation["base_sha256"] == first["sha256"]
        assert observation["system_sha256"] == system_sha256(supplied)
        assert verifier(observation, "demo", "prompt-session")
        assert first["text"] not in json.dumps(observation)
        call = next(item for item in result["session"]["trace"]
                    if item.get("type") == "llm_call" and item["id"] == observation["llm_call_id"])
        assert call["model"] == observation["model"]
    assert events(latest(runtime)["session"]) == observations
    assert (store.root / "provenance.key").read_text() not in json.dumps(result)
    assert (store.root / "provenance.key").stat().st_mode & 0o777 == 0o600


def test_restart_new_revision_keeps_old_session_binding_and_new_session_uses_new(runtime):
    directory, store, first, _ = runtime
    llm = ScriptedLLM([response("One"), response("Two"), response("Three")])
    run(runtime, factory_for(runtime, first, llm))
    second = store.save(first["id"], "Second base instructions")["current"]
    restarted = factory_for(runtime, second, llm)
    old = events(run(runtime, restarted)["session"])[-1]
    new = events(run(runtime, restarted, session={"session_id": "new-session"})["session"])[-1]
    assert old["status"] == "bound" and old["version_id"] == first["id"]
    assert old["launch_version_id"] == second["id"]
    assert new["status"] == "bound" and new["version_id"] == second["id"]
    assert llm.inputs[1][0]["content"] == first["text"]
    assert llm.inputs[2][0]["content"] == second["text"]


def test_identical_text_rollback_revision_is_not_guessed(runtime):
    _, store, first, _ = runtime
    llm = ScriptedLLM([response("One"), response("Two"), response("Three")])
    run(runtime, factory_for(runtime, first, llm))
    second = store.save(first["id"], "Different")["current"]
    restored = store.save(second["id"], restore=first["id"])["current"]
    factory = factory_for(runtime, restored, llm)
    old = events(run(runtime, factory)["session"])[-1]
    new = events(run(runtime, factory, session={"session_id": "other-session"})["session"])[-1]
    assert old["version_id"] == first["id"] and new["version_id"] == restored["id"]
    assert old["system_sha256"] == new["system_sha256"]
    assert old["launch_version_id"] == new["launch_version_id"] == restored["id"]


@pytest.mark.parametrize("forge", [False, True])
def test_old_identical_system_without_authentic_binding_is_unknown(runtime, forge):
    directory, _, first, _ = runtime
    session = {"session_id": "prompt-session", "messages": [{"role": "system", "content": first["text"]}]}
    if forge:
        session["_studio_prompt_binding"] = {
            "provenance_version": 1, "agent_slug": "demo", "session_id": "prompt-session",
            "version_id": first["id"], "base_sha256": first["sha256"],
            "system_sha256": system_sha256(session["messages"]), "_studio_signature": "0" * 64,
        }
    before = deepcopy(session)
    result = run(runtime, factory_for(runtime, first, ScriptedLLM([response("Answer")])), session=session)
    event = events(result["session"])[-1]
    assert event["status"] == "unknown" and event["version_id"] is None and event["base_sha256"] is None
    assert event["launch_version_id"] == first["id"]
    assert "_studio_prompt_binding" not in result["session"]
    assert session == before
    assert verify_event(event, agent_slug="demo", session_id="prompt-session", agent_dir=directory)


@pytest.mark.parametrize("change", ["session", "system", "proof", "revision"])
def test_signed_binding_cannot_be_moved_or_modified(runtime, change):
    _, _, first, _ = runtime
    llm = ScriptedLLM([response("One"), response("Two")])
    factory = factory_for(runtime, first, llm)
    original = run(runtime, factory)["session"]
    candidate = deepcopy(original)
    # Direct Agent.input isolates the proof check from Host's recency policy.
    if change == "session":
        candidate["session_id"] = "other-session"
    elif change == "system":
        candidate["messages"][0]["content"] = "Client substituted instructions"
    elif change == "proof":
        candidate["_studio_prompt_binding"]["_studio_signature"] = "0" * 64
    else:
        candidate["_studio_prompt_binding"]["version_id"] = "a" * 32
    agent = factory()
    agent.input("Followup", session=candidate)
    event = events(agent.current_session)[-1]
    assert event["status"] == "unknown" and event["version_id"] is None


@pytest.mark.parametrize("when", ["ready", "before", "developer"])
def test_plugin_modified_system_is_unknown_and_hashes_actual_input(runtime, when):
    _, _, first, _ = runtime

    @on_agent_ready
    def ready(agent):
        if when == "ready":
            agent.system_prompt += "\nPlugin rules"

    @before_llm
    def modify(agent):
        if when == "before":
            agent.current_session["messages"][0]["content"] += "\nPlugin rules"
        elif when == "developer":
            agent.current_session["messages"].append({"role": "developer", "content": "Extra rules"})

    llm = ScriptedLLM([response("Answer")])
    event = events(run(runtime, factory_for(runtime, first, llm, on_events=[ready, modify]))["session"])[-1]
    assert event["status"] == "unknown" and event["reason"] == "system_modified"
    assert event["version_id"] is None
    assert event["system_sha256"] == system_sha256(llm.inputs[0])


def test_multiple_calls_have_individual_observations(runtime):
    _, _, first, _ = runtime

    def lookup(value: str) -> str:
        """Return a synthetic value without network or I/O."""
        return value

    @before_llm
    def second_call_changes_system(agent):
        if agent.current_session["iteration"] > 1:
            agent.current_session["messages"][0]["content"] += " Second iteration rules"

    llm = ScriptedLLM([response(None, [ToolCall("lookup", {"value": "example"}, "tool-1")]), response("Answer")])
    result = run(runtime, factory_for(runtime, first, llm, tools=[lookup], on_events=[second_call_changes_system]))
    observed = events(result["session"])
    assert len(observed) == 2 and all(event["turn"] == 1 for event in observed)
    assert [event["status"] for event in observed] == ["bound", "unknown"]
    assert len({event["llm_call_id"] for event in observed}) == 2
    assert [event["system_sha256"] for event in observed] == [system_sha256(value) for value in llm.inputs]
    assert result["session"]["trace"][0]["type"] == "user_input"
    assert result["session"]["trace"][-1]["type"] == "turn_result"


def test_provider_attribute_writes_still_reach_real_provider(runtime):
    _, _, first, _ = runtime

    class ModelAwareLLM(ScriptedLLM):
        def complete(self, messages, **kwargs):
            assert self.model == "selected-offline-model"
            assert self.temperature == 0.2
            return super().complete(messages, **kwargs)

    @before_llm
    def choose_provider_options(agent):
        agent.llm.model = "selected-offline-model"
        agent.llm.temperature = 0.2

    provider = ModelAwareLLM([response("Answer")])
    observed = events(run(runtime, factory_for(runtime, first, provider,
                                               on_events=[choose_provider_options]))["session"])[0]
    assert observed["model"] == provider.model == "selected-offline-model"


def test_actual_interruptible_worker_carries_call_context(runtime):
    directory, _, first, storage = runtime

    class OfflineIO:
        def __init__(self):
            self.sent = []

        def send(self, event):
            self.sent.append(deepcopy(event))

        def receive_all(self, *_args):
            return []

    io = OfflineIO()
    result = input_handler(factory_for(runtime, first, ScriptedLLM([response("Answer")])), storage,
                           "Threaded call", result_ttl=3600, connection=io,
                           session={"session_id": "prompt-session"})
    observed = events(result["session"])
    assert len(observed) == 1 and observed[0]["status"] == "bound"
    assert verify_event(observed[0], agent_slug="demo", session_id="prompt-session", agent_dir=directory)
    assert any(event.get("type") == "prompt_provenance" for event in io.sent)


def test_event_signature_rejects_modified_fields_cross_session_and_cross_agent(runtime):
    directory, _, first, _ = runtime
    event = events(run(runtime, factory_for(runtime, first, ScriptedLLM([response("Answer")])))["session"])[0]
    for field, value in (("turn", 2), ("llm_call_id", "other"), ("version_id", "a" * 32),
                         ("status", "unknown"), ("system_sha256", "0" * 64), ("ts", 0)):
        changed = {**event, field: value}
        assert not verify_event(changed, agent_slug="demo", session_id="prompt-session", agent_dir=directory)
    assert not verify_event(event, agent_slug="demo", session_id="other-session", agent_dir=directory)
    assert not verify_event(event, agent_slug="other", session_id="prompt-session", agent_dir=directory)
    assert not verify_event({k: v for k, v in event.items() if k != "_studio_signature"},
                            agent_slug="demo", session_id="prompt-session", agent_dir=directory)


