@pytest.mark.parametrize("bad", ["symlink", "invalid", "permissions"])
def test_corrupt_key_fails_closed_without_reset(runtime, tmp_path, bad):
    directory, store, first, _ = runtime
    key = store.root / "provenance.key"
    if bad == "symlink":
        outside = tmp_path / "outside-key"
        outside.write_text("a" * 64)
        key.symlink_to(outside)
    else:
        key.write_text("bad" if bad == "invalid" else "a" * 64)
        key.chmod(0o600 if bad == "invalid" else 0o644)
    before = key.read_text()
