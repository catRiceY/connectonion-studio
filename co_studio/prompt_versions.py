"""Local immutable base-prompt revisions; no Agent imports, execution or history rewriting.

The selected revision is a *next launch* setting, not proof of a running or
historical session's instructions. A generated custom Agent is the only supported
integration. Version files live outside its tool workspace.
"""
from __future__ import annotations

import ast
from datetime import datetime, timezone
import functools
import hashlib
import inspect
import json
import os
from pathlib import Path
import re
import stat
import uuid

from filelock import FileLock

MAX_PROMPT_BYTES = 65536
_ID = re.compile(r"^[a-f0-9]{32}$")
_SLUG = re.compile(r"^[a-z0-9]+(?:-[a-z0-9]+)*$")
_FIELDS = {"id", "text", "created_at", "parent_id", "restored_from", "sha256"}


class PromptError(Exception):
    """Safe, fixed messages only: callers must not expose OS exceptions."""


class PromptConflict(PromptError):
    pass


class PromptUnsupported(PromptError):
    pass


class PromptInvalid(PromptError):
    pass


class PromptNotFound(PromptError):
    pass


def normalize_text(text: str) -> str:
    if not isinstance(text, str) or "\x00" in text:
        raise PromptInvalid("Prompt must be UTF-8 text without NUL characters")
    try:
        size = len(text.encode("utf-8"))
    except UnicodeError:
        raise PromptInvalid("Prompt must be valid UTF-8 text") from None
    if size > MAX_PROMPT_BYTES:
        raise PromptInvalid("Prompt must be at most 64 KiB in UTF-8")
    text = text.strip()  # ConnectOnion's explicit Path loader uses this normalization.
    if not text:
        raise PromptInvalid("Prompt must not be empty")
    return text


def _sha(text: str) -> str:
    return hashlib.sha256(text.encode("utf-8")).hexdigest()


def _safe(path: Path) -> Path:
    if path.resolve() != path:
        raise PromptError("Linked prompt paths are not supported")
    return path


def _read(path: Path, limit: int) -> str:
    _safe(path)
    try:
        fd = os.open(path, os.O_RDONLY | getattr(os, "O_NOFOLLOW", 0) | getattr(os, "O_NONBLOCK", 0))
        with os.fdopen(fd, "rb") as stream:
            info = os.fstat(stream.fileno())
            if not stat.S_ISREG(info.st_mode) or info.st_size > limit:
                raise PromptError("Prompt storage contains an invalid file")
            data = stream.read(limit + 1)
        if len(data) > limit:
            raise PromptError("Prompt storage contains an oversized file")
        return data.decode("utf-8")
    except (OSError, UnicodeError):
        raise PromptError("Prompt storage is unavailable") from None


def _json(path: Path, limit: int = MAX_PROMPT_BYTES * 7) -> dict:
    try:
        value = json.loads(_read(path, limit))
    except (ValueError, RecursionError):
        raise PromptError("Prompt storage contains invalid data") from None
    if not isinstance(value, dict):
        raise PromptError("Prompt storage contains invalid data")
    return value


def _new_file(path: Path, text: str) -> None:
    _safe(path)
    fd = os.open(path, os.O_WRONLY | os.O_CREAT | os.O_EXCL | getattr(os, "O_NOFOLLOW", 0), 0o600)
    with os.fdopen(fd, "w", encoding="utf-8") as stream:
        stream.write(text)
        stream.flush()
        os.fsync(stream.fileno())


def _baseline(script: Path) -> dict:
    """Recognize the generated factory shape without importing/executing it."""
    try:
        tree = ast.parse(_read(script, 512 * 1024))
        doc = ast.get_docstring(tree) or ""
        assignments = [node for node in tree.body if isinstance(node, ast.Assign)
                       and any(isinstance(t, ast.Name) and t.id == "SYSTEM_PROMPT" for t in node.targets)]
        factories = [node for node in tree.body if isinstance(node, ast.FunctionDef) and node.name == "create_agent"]
        imported = any(isinstance(node, ast.ImportFrom) and node.module == "connectonion"
                       and any(alias.name == "Agent" and alias.asname is None for alias in node.names)
                       for node in tree.body)
        if "generated by ConnectOnion Studio" not in doc or len(assignments) != 1 or len(factories) != 1 or not imported:
            raise PromptUnsupported("Prompt editing supports generated custom Agents only")
        factory = factories[0]
        calls = [node for node in ast.walk(factory) if isinstance(node, ast.Call)
                 and isinstance(node.func, ast.Name) and node.func.id == "Agent"]
        args = factory.args
        if (factory.decorator_list or args.posonlyargs or args.args or args.kwonlyargs
                or args.vararg or args.kwarg or len(calls) != 1
                or not any(kw.arg == "system_prompt" and isinstance(kw.value, ast.Name)
                           and kw.value.id == "SYSTEM_PROMPT" for kw in calls[0].keywords)
                or any(isinstance(node, ast.Name) and node.id == "SYSTEM_PROMPT"
                       and isinstance(node.ctx, ast.Store) for node in ast.walk(factory))):
            raise PromptUnsupported("This custom Agent factory is not supported for Prompt editing")
        text = normalize_text(ast.literal_eval(assignments[0].value))
    except (SyntaxError, ValueError, TypeError, RecursionError, PromptInvalid):
        raise PromptUnsupported("The generated Agent has no supported literal system prompt") from None
    return {"id": "baseline", "text": text, "created_at": None,
            "parent_id": None, "restored_from": None, "sha256": _sha(text)}


class PromptVersions:
    def __init__(self, agent_dir: Path):
        self.agent_dir = Path(agent_dir).absolute()
        _safe(self.agent_dir)
        if not _SLUG.fullmatch(self.agent_dir.name):
            raise PromptInvalid("Invalid Agent identifier")
        self.script = self.agent_dir / "agent.py"
        self.root = self.agent_dir / ".studio-prompts"
        self.pointer = self.root / "current.json"

    def _supported_baseline(self) -> dict:
        meta = _json(self.agent_dir / "meta.json", 128 * 1024)
        if meta.get("slug") != self.agent_dir.name:
            raise PromptError("Agent metadata does not match its directory")
        if meta.get("preset", "custom") != "custom":
            raise PromptUnsupported("Prompt editing is currently available for custom Agents only; co-ai is not supported")
        return _baseline(self.script)

    def _has_pointer(self) -> bool:
        _safe(self.root)
        _safe(self.pointer)
        if self.root.exists() and not self.root.is_dir():
            raise PromptError("Prompt storage is unavailable")
        return self.pointer.exists()

    def _version(self, version_id: str) -> dict:
        if version_id != "baseline" and not _ID.fullmatch(version_id):
            raise PromptNotFound("Prompt version not found")
        record = _json(self.root / f"{version_id}.json")
        try:
            valid = (set(record) == _FIELDS and record["id"] == version_id
                     and normalize_text(record["text"]) == record["text"]
                     and record["sha256"] == _sha(record["text"]))
            if version_id == "baseline":
                valid = valid and all(record[key] is None for key in ("created_at", "parent_id", "restored_from"))
            else:
                valid = valid and isinstance(record["created_at"], str)
                # Parent/restore references never become arbitrary paths.
                valid = valid and (record["parent_id"] == "baseline" or bool(_ID.fullmatch(record["parent_id"])))
                valid = valid and (record["restored_from"] is None or record["restored_from"] == "baseline"
                                   or bool(_ID.fullmatch(record["restored_from"])))
                if valid:
                    valid = datetime.fromisoformat(record["created_at"]).tzinfo is not None
            if not valid or _read(self.root / f"{version_id}.prompt", MAX_PROMPT_BYTES) != record["text"]:
                raise PromptError("Prompt version failed integrity validation")
        except (KeyError, TypeError, ValueError, PromptInvalid):
            raise PromptError("Prompt version failed integrity validation") from None
        return record

    def _records(self, baseline: dict) -> list[dict]:
        if not self._has_pointer():
            return [baseline]
        pointer = _json(self.pointer, 1024)
        identity = pointer.get("version_id")
        if set(pointer) != {"version_id"} or not isinstance(identity, str) or not _ID.fullmatch(identity):
            raise PromptError("Prompt selection failed integrity validation")
        records, seen = [], set()
        while identity != "baseline":
            if identity in seen or len(seen) >= 1000:
                raise PromptError("Prompt version chain is invalid or too large")
            seen.add(identity)
            record = self._version(identity)
            records.append(record)
            identity = record["parent_id"]
        records.append(self._version("baseline"))
        available = {record["id"] for record in records}
        if any(record["restored_from"] is not None and record["restored_from"] not in available for record in records):
            raise PromptError("Prompt restore reference is unavailable")
        return records

    def state(self) -> dict:
        try:
            baseline = self._supported_baseline()
        except PromptUnsupported as exc:
            return {"supported": False, "reason": str(exc), "current": None, "versions": []}
        records = self._records(baseline)
        return {"supported": True, "reason": None, "current": records[0],
                "versions": [{key: value for key, value in record.items() if key != "text"}
                             for record in records if record["id"] != "baseline"]}

    def get(self, version_id: str) -> dict:
        records = self._records(self._supported_baseline())
        for record in records:
            if record["id"] == version_id:
                return record
        raise PromptNotFound("Prompt version not found")

    def save(self, base_version: str, text: str | None = None, *, restore: str | None = None) -> dict:
        # Registry mutations use another lock. Never nest registry.locked() here.
        lock = _safe(self.agent_dir / ".studio-prompts.lock")
        self._supported_baseline()
        try:
            with FileLock(str(lock), timeout=10):
                baseline = self._supported_baseline()
                records = self._records(baseline)
                if records[0]["id"] != base_version:
                    raise PromptConflict("Prompt changed since it was opened; reload before saving")
                if len(records) > 1000:
                    raise PromptConflict("Prompt version limit reached")
                if restore is not None:
                    old = next((item for item in records if item["id"] == restore), None)
                    if old is None:
                        raise PromptNotFound("Prompt version not found")
                    text = old["text"]
                text = normalize_text(text)
                _safe(self.root).mkdir(mode=0o700, exist_ok=True)
                if not self._has_pointer():
                    for suffix, data in (("prompt", baseline["text"]), ("json", json.dumps(baseline, ensure_ascii=False))):
                        path = self.root / f"baseline.{suffix}"
                        if path.exists():
                            if _read(path, MAX_PROMPT_BYTES * 7) != data:
                                raise PromptError("Uncommitted baseline does not match the Agent")
                        else:
                            _new_file(path, data)
                record = {"id": uuid.uuid4().hex, "text": text,
                          "created_at": datetime.now(timezone.utc).isoformat(),
                          "parent_id": base_version, "restored_from": restore, "sha256": _sha(text)}
                _new_file(self.root / f"{record['id']}.prompt", text)
                _new_file(self.root / f"{record['id']}.json", json.dumps(record, ensure_ascii=False))
                temporary = self.root / f"current-{uuid.uuid4().hex}.tmp"
                _new_file(temporary, json.dumps({"version_id": record["id"]}))
                _safe(self.pointer)
                os.replace(temporary, self.pointer)
                return self.state()
        except (OSError, TimeoutError):
            raise PromptError("Prompt version could not be saved") from None


def wrap_host_for_prompt(host_fn, script: Path):
    """Freeze selection once per launch; affect only the recognized custom factory.

    No rewrite of agent.py, no global Agent replacement, and no inference about
    existing sessions. ConnectOnion intentionally restores their old system text.
    """
    script = Path(script).absolute()
    root = script.parent / ".studio-prompts"
    # Unmanaged/legacy scripts can live outside slug-named registry folders.
    # Do not impose the Prompt schema until a selection actually exists.
    if not os.path.lexists(root):
        return host_fn
    _safe(root)
    if not root.is_dir():
        raise PromptError("Prompt storage is unavailable")
    pointer = _safe(root / "current.json")
    if not pointer.exists():
        return host_fn
    store = PromptVersions(script.parent)
    if not store._has_pointer():
        return host_fn  # Preserve all legacy/standalone behavior when not enabled.
    baseline = store._supported_baseline()
    frozen = store._records(baseline)[0]
    prompt_path = store.root / f"{frozen['id']}.prompt"

    @functools.wraps(host_fn)
    def wrapped(factory, *args, **kwargs):
        namespace = getattr(factory, "__globals__", {})
        co_dir = kwargs.get("co_dir")
        if (not inspect.isfunction(factory) or factory.__name__ != "create_agent"
                or Path(factory.__code__.co_filename).absolute() != script
                or Path(namespace.get("__file__", "")).absolute() != script
                or co_dir is None or Path(co_dir).absolute() != script.parent / ".co"
                or not isinstance(namespace.get("SYSTEM_PROMPT"), str)
                or namespace["SYSTEM_PROMPT"].strip() != baseline["text"]):
            raise PromptUnsupported("Selected Prompt cannot be applied to this Agent factory")
        _safe(Path(co_dir).absolute())
        _baseline(script)  # Reject a changed/unsupported script, never silently fall back.
        namespace["SYSTEM_PROMPT"] = prompt_path

        @functools.wraps(factory)
        def frozen_factory():
            # A later pointer edit cannot switch this process. Tampered files fail closed.
            record = store._version(frozen["id"])
            if record != frozen:
                raise PromptError("Selected Prompt changed after launch")
            from .prompt_provenance import attach_provenance
            return attach_provenance(factory(), agent_dir=store.agent_dir, revision=frozen)

        return host_fn(frozen_factory, *args, **kwargs)

    return wrapped
